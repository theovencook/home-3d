/** The page's text for a key: its own (st_…) in English or German, else the main texts (`t`). */
export function settingsTexts(t: (key: string, vars?: Record<string, string | number>) => string, language: () => string | undefined) {
  return (key: string, vars: Record<string, string | number> = {}): string => {
    if (!key.startsWith("st_")) return t(key, vars);
    const table = (language() ?? "").startsWith("de") ? SETTINGS_DE : SETTINGS_EN;
    let out = table[key] ?? SETTINGS_EN[key] ?? key;
    for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
    return out;
  };
}
