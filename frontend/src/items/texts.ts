/** The editor's text for a key: the main texts first (sections, rooms, colour roles), then its own. */
export function itemTexts(t: (key: string, vars?: Record<string, string | number>) => string, language: () => string | undefined) {
  return (key: string, vars: Record<string, string | number> = {}): string => {
    if (!key.startsWith("ie_")) return t(key, vars);
    const table = (language() ?? "").startsWith("de") ? ITEMS_DE : ITEMS_EN;
    let out = table[key] ?? ITEMS_EN[key] ?? key;
    for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
    return out;
  };
}
