def car_id(brand_id: str, name: str) -> str:
    """The item id of a car: brand and model as a slug ("ford_mustang_mach_e")."""
    slug = "".join(c if c.isalnum() else "_" for c in name.lower())
    return f"{brand_id}_{'_'.join(p for p in slug.split('_') if p)}"[:40]
